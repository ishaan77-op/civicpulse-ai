# Test 9: Multiple work updates can exist for the same complaint.
# ---------------------------------------------------------------------------

def test_multiple_work_updates_for_same_complaint(client, app, citizen_user, officer_user):
    complaint_id = _make_complaint(app, citizen_user)
    token = get_token(client, "officer@example.com", "officer123")
    headers = {"Authorization": f"Bearer {token}"}

    client.post(
        f"/api/officers/complaints/{complaint_id}/work-updates",
        data={"status": "In Progress", "note": "Work started."},
        content_type="multipart/form-data",
        headers=headers,
    )
    client.post(
        f"/api/officers/complaints/{complaint_id}/work-updates",
        data={"status": "In Progress", "note": "Base layer done."},
        content_type="multipart/form-data",
        headers=headers,
    )

    res = client.get(
        f"/api/officers/complaints/{complaint_id}/work-updates",
        headers=headers,
    )
    assert res.status_code == 200
    body = res.get_json()
    assert body["total"] == 2
    assert len(body["work_updates"]) == 2
    notes = [wu["note"] for wu in body["work_updates"]]
    assert "Work started." in notes
    assert "Base layer done." in notes


