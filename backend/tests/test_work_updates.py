def test_work_update_timestamp_is_server_generated(client, app, citizen_user, officer_user):
    """The API response must include a valid ISO-8601 timestamp. The client
    never supplied one, so any valid timestamp in the response proves the
    server generated it."""
    complaint_id = _make_complaint(app, citizen_user)
    token = get_token(client, "officer@example.com", "officer123")

    res = client.post(
        f"/api/officers/complaints/{complaint_id}/work-updates",
        data={"status": "In Progress", "note": "Server time check."},
        content_type="multipart/form-data",
        headers={"Authorization": f"Bearer {token}"},
    )
    assert res.status_code == 201
    ts = res.get_json()["work_update"]["created_at"]
    assert ts is not None
    # Must parse as a valid datetime.
    parsed = datetime.fromisoformat(ts)
    assert parsed is not None


