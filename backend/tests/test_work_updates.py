# Test 1 & 2: Officer can submit a valid work update and it is persisted.
# ---------------------------------------------------------------------------

def test_officer_can_submit_work_update(client, app, citizen_user, officer_user):
    """Test 1 & 2: Valid submission returns 201 and the record is in the DB."""
    complaint_id = _make_complaint(app, citizen_user)
    token = get_token(client, "officer@example.com", "officer123")

    res = client.post(
        f"/api/officers/complaints/{complaint_id}/work-updates",
        data={
            "status": "In Progress",
            "note": "Road repair work started.",
        },
        content_type="multipart/form-data",
        headers={"Authorization": f"Bearer {token}"},
    )

    assert res.status_code == 201, res.get_json()
    body = res.get_json()
    assert body["work_update"]["id"] is not None

    # Test 2: persisted in DB
    with app.app_context():
        wu = ComplaintWorkUpdate.query.get(body["work_update"]["id"])
        assert wu is not None
        assert wu.note == "Road repair work started."


