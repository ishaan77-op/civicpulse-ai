def get_token(client, email, password):
    res = client.post("/api/auth/login", json={"email": email, "password": password})
    return res.get_json()["token"]


def fake_image(name="photo.jpg"):
    return (io.BytesIO(b"fake-image-bytes"), name)


def _make_complaint(app, citizen_user):
    """Create a minimal complaint row directly in the DB (no AI call needed)."""
    with app.app_context():
        issue = CivicIssue(
            category="Road Infrastructure",
            latitude=20.0,
            longitude=73.8,
            location_label="Test Rd",
            ai_summary="Test issue",
        )
        db.session.add(issue)
        db.session.flush()

        c = Complaint(
            title="Pothole on Test Rd",
            description="Big hole",
            category="Road Infrastructure",
            location="Test Rd",
            latitude=20.0,
            longitude=73.8,
            user_id=citizen_user.id,
            issue_id=issue.id,
        )
        db.session.add(c)
        db.session.commit()
        return c.id


