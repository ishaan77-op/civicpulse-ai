def test_resolved_status_rejected_for_work_updates(client, app, citizen_user, officer_user):
    """'Resolved' is not permitted for ordinary work updates. Requests with
    status='Resolved' must return 400, must NOT create a work update record,
    and must NOT modify complaint.status."""
    complaint_id = _make_complaint(app, citizen_user)
    token = get_token(client, "officer@example.com", "officer123")

    with app.app_context():
        initial_complaint = Complaint.query.get(complaint_id)
        initial_status = initial_complaint.status
        initial_update_count = ComplaintWorkUpdate.query.filter_by(
            complaint_id=complaint_id
        ).count()

    res = client.post(
        f"/api/officers/complaints/{complaint_id}/work-updates",
        data={"status": "Resolved", "note": "Trying to mark as resolved."},
        content_type="multipart/form-data",
        headers={"Authorization": f"Bearer {token}"},
    )
    assert res.status_code == 400
    body = res.get_json()
    assert body["message"] == "Invalid status"
    assert "Resolved" not in body["allowed_statuses"]
    assert body["allowed_statuses"] == ["Pending", "In Progress"]

    with app.app_context():
        complaint = Complaint.query.get(complaint_id)
        # Assert authoritative status unchanged
        assert complaint.status == initial_status
        # Assert no work-update record created
        updates_count = ComplaintWorkUpdate.query.filter_by(
            complaint_id=complaint_id
        ).count()
        assert updates_count == initial_update_count


